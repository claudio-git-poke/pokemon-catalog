import { test } from 'node:test'
import assert from 'node:assert/strict'
import { PGlite } from '@electric-sql/pglite'
import { readFile } from 'node:fs/promises'
import { postgresClient } from './helpers/postgres-client.mjs'
import { SOURCES } from '../scripts/catalog-core.mjs'
import { syncCatalog } from '../scripts/sync-catalog.mjs'
test('worker imports, reconciles, retries, excludes Pocket and preserves a concurrent manual image',async()=>{
 const pg=new PGlite()
 try {
  await pg.exec(`create role anon;create role authenticated;create role service_role bypassrls;
   create table cards(id bigint generated by default as identity primary key,file_name text,sigla text,lingua text,numero integer,variante text,codice text,nome text,link_cardmarket text,image_url text,image_status text,image_source text,notes text);
   insert into cards(file_name,sigla,lingua,numero,variante,nome,image_status) values('MFB_001.jpg','MFB','INT',1,'normale','Arcanine','missing');`)
  await pg.exec(await readFile(new URL('../db/automazione.sql',import.meta.url),'utf8'))
  await pg.exec(await readFile(new URL('../db/log-events.sql',import.meta.url),'utf8'))
  const db=postgresClient(pg)
  let searches=0
  let extended = false
  const fetchSource=async path=>{
   if(path.endsWith('/sets'))return [{id:'mfb',name:'My First Battle',cardCount:{total:extended && path.startsWith('en/') ? 2 : 1}},{id:'A1',name:'Pocket'}]
   if(path.endsWith('/A1'))return {serie:{id:'tcgp'},cards:[{id:'A1-001',localId:'001',name:'Pocket only'}]}
   return {serie:{id:'misc'},cards:[{id:'mfb-14',localId:'14',name:'Arcanine'}, ...(extended && path.startsWith('en/') ? [{id:'mfb-10',localId:'10',name:'Charmeleon'}] : [])]}
  }
  const search=async card=>{searches++;return {url:null,message:'Not yet available'}}
  const first=await syncCatalog({db,fetchSource,search})
  assert.equal(first.linked,1);assert.equal(first.added,SOURCES.length-1)
  const logged=(await pg.query('select summary from catalog_sync_runs order by id desc limit 1')).rows[0].summary
  const events=(await pg.query('select message from catalog_sync_events where run_id=1 order by id')).rows
  assert.ok(events.some(e=>e.message.includes('Collegata carta esistente')))
  assert.ok(events.some(e=>e.message.includes('Ricerca immagini')))
  assert.equal(logged.events,undefined)
  assert.equal(logged.current,'Esecuzione conclusa')
  assert.equal(logged.added,first.added)
  const legacy=(await pg.query('select * from cards where id=1')).rows[0]
  assert.equal(legacy.file_name,'MFB_001.jpg');assert.equal(legacy.source_card_id,'mfb-14');assert.equal(legacy.image_status,'placeholder')
  assert.equal((await pg.query("select count(*)::int n from cards where nome='Pocket only'")).rows[0].n,0)
  const second=await syncCatalog({db,fetchSource,search})
  assert.equal(second.added,0);assert.equal(searches,SOURCES.length)
  // Make old sets due again: no duplicates after a complete second scan.
  await pg.exec("update catalog_sync_sets set next_sync_at=now() where set_id='mfb'")
  const third=await syncCatalog({db,fetchSource,search})
  assert.equal(third.added,0);assert.equal((await pg.query('select count(*)::int n from cards')).rows[0].n,SOURCES.length)
  await pg.exec("update cards set image_next_attempt_at=now() where id=1")
  const fail=await syncCatalog({db,fetchSource,search:async()=>{throw Error('Temporary 503')}})
  const errored=(await pg.query('select * from cards where id=1')).rows[0]
  assert.equal(fail.errors,1);assert.match(errored.image_last_error,/503/);assert.equal(errored.image_status,'placeholder')
  assert.ok(Date.parse(errored.image_next_attempt_at)>Date.now())
  await pg.exec("update cards set image_next_attempt_at=now() where id=1")
  await syncCatalog({db,fetchSource,search:async()=>{
   await pg.exec("update cards set image_status='manual',image_url='https://example.com/manual.jpg' where id=1")
   return {url:'https://example.com/auto.jpg',source:'tcgdex',message:'Found'}
  }})
  const manual=(await pg.query('select image_url,image_status from cards where id=1')).rows[0]
  assert.equal(manual.image_status,'manual');assert.equal(manual.image_url,'https://example.com/manual.jpg')
  // A later daily discovery sees a changed count and imports a new card from an existing set.
  extended=true
  await pg.exec("update catalog_sync_sets set last_sync_at='2020-01-01' where set_id='__index__'")
  const updated=await syncCatalog({db,fetchSource,search})
  assert.equal(updated.added,1)
  assert.equal((await pg.query("select count(*)::int n from cards where source_uid='tcgdex:en:mfb-10'")).rows[0].n,1)
  await pg.exec("insert into cards(nome,image_status,image_url) values('Senza URL','found',null),('Manuale','manual',null)")
  await syncCatalog({db,fetchSource,search})
  const absent=(await pg.query("select image_status from cards where nome='Senza URL'")).rows[0]
  assert.equal(absent.image_status,'placeholder')
  assert.equal((await pg.query("select image_status from cards where nome='Manuale'")).rows[0].image_status,'manual')


 }finally{await pg.close()}
})
