import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { PGlite } from '@electric-sql/pglite'
test('SQL setup is repeatable, preserves original cards, enforces source identity and read-only status',async()=>{
 const db=new PGlite()
 try {
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
    create table public.cards(id bigint generated by default as identity primary key, image_status text, nome text);
    insert into public.cards(id,image_status,nome) values(7210,'manual','Carta originale');`)
  const sql=await readFile(new URL('../db/automazione.sql',import.meta.url),'utf8')
  await db.exec(sql); await db.exec(sql)
  await db.exec(`insert into public.cards(source_uid,nome,image_status) values('tcgdex:en:test-1','Nuova carta','missing')`)
  const rows=await db.query('select id,nome from public.cards order by id')
  assert.deepEqual(rows.rows.map(r=>r.id),[7210,7211])
  await assert.rejects(db.exec(`insert into public.cards(source_uid) values('tcgdex:en:test-1')`),/unique/)
  await db.exec('set role anon; select * from public.catalog_sync_runs;')
  await assert.rejects(db.exec(`insert into public.catalog_sync_runs(status) values('fake')`),/permission denied/)
 } finally {await db.close()}
})
