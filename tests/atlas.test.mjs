import { test } from 'node:test'
import assert from 'node:assert/strict'
import { mkdtemp,mkdir,readFile,writeFile,rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { PGlite } from '@electric-sql/pglite'
import { atlasSets,atlasCards,importAtlasSet } from '../scripts/atlas-source.mjs'
import { syncCatalog } from '../scripts/sync-catalog.mjs'
import { newCard } from '../scripts/catalog-core.mjs'
import { externalImages } from '../src/lib/external-cards.ts'
import { aggressiveSearch } from '../src/lib/image-search.ts'
import { postgresClient } from './helpers/postgres-client.mjs'

test('actual JP/KO/Taiwan records normalize, supplement existing cards and never cross languages',async()=>{
 const root=await mkdtemp(path.join(tmpdir(),'bindex-atlas-')); const pg=new PGlite()
 try {
  for(const [folder,set,file] of [['jp','S8a','40088'],['ko','M1L','001'],['tc','M1L','001']]){
   const dir=path.join(root,`data_${folder}`,set);await mkdir(dir,{recursive:true})
   await writeFile(path.join(dir,`${file}.json`),await readFile(new URL(`fixtures/atlas-${folder}.json`,import.meta.url)))
  }
  const sets=await atlasSets(root);assert.equal(sets.length,3)
  const jpSet=sets.find(s=>s.source_language==='ja')
  const jp=(await atlasCards(root,jpSet))[0]
  assert.equal(jp.localId,'023');assert.equal(jp.localLanguage,'JP')
  await pg.exec(`create role anon;create role authenticated;create role service_role bypassrls;
   create table cards(id bigint generated by default as identity primary key,file_name text,sigla text,lingua text,numero integer,variante text,codice text,nome text,link_cardmarket text,image_url text,image_status text,image_source text,notes text);`)
  await pg.exec(await readFile(new URL('../db/automazione.sql',import.meta.url),'utf8'))
  await pg.exec("insert into cards(sigla,lingua,numero,variante,nome,image_status,source_uid,source_local_id) values('S8A@JP','JP',23,'normale','Flying Pikachu V','missing','tcgdex:ja:S8a-023','023')")
  const db=postgresClient(pg), summary={added:0,linked:0,processedSets:0,ambiguous:0}
  for(const set of sets)await db.from('catalog_sync_sets').insert(set)
  for(const set of sets)await importAtlasSet({db,set,root,newCard,summary,deadline:Date.now()+600000})
  assert.equal(summary.added,2);assert.equal(summary.alternatives,1)
  // Repeat all imports: source identities stay stable and no duplicate is created.
  for(const set of sets)await importAtlasSet({db,set,root,newCard,summary,deadline:Date.now()+600000})
  assert.equal((await pg.query('select count(*)::int n from cards')).rows[0].n,3)
  const legacy=(await pg.query("select * from cards where lingua='JP'")).rows[0]
  const candidates=await externalImages(db,legacy);assert.equal(candidates.length,1)
  assert.match(candidates[0].url,/www.pokemon-card.com/)
  const realFetch=globalThis.fetch; let calls=0
  try {
   globalThis.fetch=async()=>{calls++;return new Response('',{headers:{'content-type':'image/jpeg'}})}
   const found=await aggressiveSearch(legacy,{externalCandidates:candidates});assert.equal(found.source,'atlas-official-ja');assert.equal(calls,1)
  } finally {globalThis.fetch=realFetch}
  const korean=(await pg.query("select * from cards where lingua='KOR'")).rows[0]
  assert.match((await externalImages(db,korean))[0].url,/pokemonkorea/)
  // Different official pictures for one printed number require review.
  await pg.exec("insert into catalog_external_cards(source_uid,provider,language,set_code,local_id,name,image_url) values('other','atlas-official-ja','JP','s8a','23','Alternate','https://www.pokemon-card.com/other.jpg')")
  assert.equal((await externalImages(db,legacy)).length,0)
  // TCGdex discovering the same Korean card later must preserve its Atlas identity.
  const before=korean.source_uid
  const result=await syncCatalog({db,atlasRoot:null,fetchSource:async p=>p.endsWith('/sets')?[{id:'M1L',name:'Test set'}]:{cards:[{id:'M1L-001',localId:'001',name:'Bulbasaur'}]},search:async()=>({url:null,message:'Test: missing'})})
  assert.equal(result.errors,0)
  assert.equal((await pg.query("select source_uid from cards where lingua='KOR'")).rows[0].source_uid,before)
  assert.equal((await pg.query("select count(*)::int n from cards where lingua='KOR'")).rows[0].n,1)

 }finally{await pg.close();await rm(root,{recursive:true,force:true})}
})

test('wrong-language records and non-official URLs are rejected; unnumbered JP energy is retained by official ID',async()=>{
 const root=await mkdtemp(path.join(tmpdir(),'bindex-atlas-'))
 try {
  const dir=path.join(root,'data_jp','S8a');await mkdir(dir,{recursive:true})
  const base=JSON.parse(await readFile(new URL('fixtures/atlas-jp.json',import.meta.url)))
  await writeFile(path.join(dir,'wrong.json'),JSON.stringify({...base,jp_id:null,lang:'ko'}))
  await writeFile(path.join(dir,'unsafe.json'),JSON.stringify({...base,img:'http://localhost/internal'}))
  await writeFile(path.join(dir,'energy.json'),JSON.stringify({...base,number:null,name:'Energy'}))
  const cards=await atlasCards(root,{source_language:'ja',set_id:'S8a'})
  assert.equal(cards.length,1);assert.equal(cards[0].localId,'UNNUMBERED:energy')
 }finally{await rm(root,{recursive:true,force:true})}
})
