-- Registro incrementale: lettura pubblica, scrittura solo dal worker.
create table if not exists public.catalog_sync_events (
  id bigint generated by default as identity primary key,
  run_id bigint not null references public.catalog_sync_runs(id) on delete cascade,
  at timestamptz not null,
  message text not null,
  event_key text not null,
  unique(run_id,event_key)
);
create index if not exists catalog_sync_events_run_cursor on public.catalog_sync_events(run_id,id);
alter table public.catalog_sync_events enable row level security;
revoke all on public.catalog_sync_events from anon,authenticated;
grant select on public.catalog_sync_events to anon,authenticated;
grant all on public.catalog_sync_events to service_role;
grant usage,select on sequence public.catalog_sync_events_id_seq to service_role;
drop policy if exists catalog_events_read on public.catalog_sync_events;
create policy catalog_events_read on public.catalog_sync_events for select to anon,authenticated using(true);
-- Compatibilità con le sessioni lunghe già attive: trasforma i nuovi eventi JSON
-- in righe incrementali senza interrompere il worker o duplicare il registro.
create or replace function public.catalog_legacy_events() returns trigger
language plpgsql set search_path = '' as $$
begin
  if jsonb_typeof(new.summary->'events') = 'array' then
    insert into public.catalog_sync_events(run_id,at,message,event_key)
    select new.id,(e->>'at')::timestamptz,e->>'message',md5((e->>'at') || ':' || (e->>'message'))
    from jsonb_array_elements(new.summary->'events') e
    where e->>'at' >= coalesce(old.summary->>'updated_at','')
    on conflict(run_id,event_key) do nothing;
  end if;
  return new;
end $$;
drop trigger if exists catalog_legacy_events on public.catalog_sync_runs;
create trigger catalog_legacy_events after update of summary on public.catalog_sync_runs for each row execute function public.catalog_legacy_events();
insert into public.catalog_sync_events(run_id,at,message,event_key)
select r.id,(e->>'at')::timestamptz,e->>'message',md5((e->>'at') || ':' || (e->>'message'))
from public.catalog_sync_runs r cross join lateral jsonb_array_elements(coalesce(r.summary->'events','[]'::jsonb)) e
order by r.id,e->>'at'
on conflict(run_id,event_key) do nothing;
